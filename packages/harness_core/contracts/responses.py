"""Response schemas for HarnessX agent engine."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from packages.harness_core.contracts.enums import (
    ContextStrategy,
    ExecutionStatus,
    HarnessMode,
)


class DiagnosticResult(BaseModel):
    """Structured code diagnostic captured by AgentGuard."""
    file_path: str = Field(..., description="Target file path.")
    line_number: Optional[int] = Field(None, description="1-indexed line number if known.")
    error_type: str = Field(..., description="Category: SyntaxError, IndentationError, LintWarning.")
    message: str = Field(..., description="Diagnostic detail or compiler message.")
    severity: str = Field("error", description="error or warning.")
    source: str = Field("ast_syntax", description="Diagnostic provider (ast_syntax, ruff).")


class ToolExecutionResult(BaseModel):
    """Output of a tool execution intercepted and verified by AgentGuard."""
    tool_name: str = Field(..., description="Tool name executed.")
    success: bool = Field(..., description="Whether the tool execution succeeded.")
    output: Any = Field("", description="Standard output or return payload.")
    error: Optional[str] = Field(None, description="Error message if execution failed.")
    duration_ms: float = Field(0.0, description="Execution duration in milliseconds.")
    files_touched: List[str] = Field(default_factory=list, description="Files created, read, or modified.")
    diagnostics: List[DiagnosticResult] = Field(default_factory=list, description="Post-execution diagnostics.")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional tool metadata.")


# Normalized alias
ToolResult = ToolExecutionResult


class ContextStatistics(BaseModel):
    """Real-time context window usage statistics."""
    total_tokens: int = Field(0, description="Current total tokens in context window.")
    window_limit: int = Field(128000, description="Model context window limit.")
    utilization_pct: float = Field(0.0, description="Token utilization percentage (0.0 to 1.0).")
    elided_count: int = Field(0, description="Number of historical tool observations elided.")
    summarized_count: int = Field(0, description="Number of times LLM summarization was triggered.")
    tokens_saved_estimate: int = Field(0, description="Estimated tokens saved by ContextT4.")
    is_estimated: bool = Field(True, description="True if estimated via fallback tokenizer, False if provider exact.")


class PerformanceMetrics(BaseModel):
    """Aggregated execution metrics for telemetry and BigQuery export."""
    input_tokens: int = Field(0, description="Cumulative input tokens sent to model.")
    output_tokens: int = Field(0, description="Cumulative output tokens generated by model.")
    total_tokens: int = Field(0, description="Total tokens processed.")
    estimated_cost_usd: float = Field(0.0, description="Estimated inference cost in USD.")
    tool_call_count: int = Field(0, description="Total tool invocations.")
    repeated_call_count: int = Field(0, description="Identified repeated/redundant tool calls.")
    diagnostic_count: int = Field(0, description="Syntactic/lint diagnostics generated.")
    recovery_count: int = Field(0, description="Self-correction attempts executed.")
    execution_duration_seconds: float = Field(0.0, description="Total elapsed execution time in seconds.")
    tokens_saved_estimate: int = Field(0, description="Estimated tokens saved via context elision.")
    final_status: ExecutionStatus = Field(ExecutionStatus.PENDING, description="Final status.")


# Alias for contract compatibility
ExecutionMetrics = PerformanceMetrics


class TaskPlanStep(BaseModel):
    """Individual step in the structured task plan."""
    step_number: int = Field(..., description="Step sequence index.")
    description: str = Field(..., description="Step objective description.")
    tool_suggested: Optional[str] = Field(None, description="Suggested tool name.")
    status: str = Field("PENDING", description="Step status: PENDING, IN_PROGRESS, COMPLETED, FAILED.")
    notes: Optional[str] = Field(None, description="Execution notes or observations.")


class ExecutionReport(BaseModel):
    """Comprehensive final report generated at session conclusion."""
    session_id: str = Field(..., description="Session identifier.")
    task: str = Field(..., description="Original user task prompt.")
    status: ExecutionStatus = Field(..., description="Terminal status.")
    harness_mode: HarnessMode = Field(..., description="Harness mode used.")
    context_strategy: ContextStrategy = Field(..., description="Context strategy used.")
    plan: List[TaskPlanStep] = Field(default_factory=list, description="Step plan executed.")
    completed_steps: List[str] = Field(default_factory=list, description="List of completed steps.")
    files_created: List[str] = Field(default_factory=list, description="Files newly created.")
    files_modified: List[str] = Field(default_factory=list, description="Files edited.")
    errors_encountered: List[str] = Field(default_factory=list, description="Errors handled during execution.")
    diagnostics_resolved: int = Field(0, description="Count of code diagnostics resolved.")
    metrics: PerformanceMetrics = Field(default_factory=PerformanceMetrics, description="Aggregated metrics.")
    summary: str = Field("", description="Executive summary of execution and outcomes.")


class AgentExecutionResponse(BaseModel):
    """Top-level response returned by HarnessEngine.run_task."""
    session_id: str = Field(..., description="Unique session ID.")
    task: str = Field(..., description="Task requested.")
    status: ExecutionStatus = Field(..., description="Final status.")
    final_result: Optional[str] = Field(None, description="Agent's final message or code solution summary.")
    report: Optional[ExecutionReport] = Field(None, description="Detailed execution report.")
    metrics: PerformanceMetrics = Field(default_factory=PerformanceMetrics, description="Execution metrics.")
    error: Optional[str] = Field(None, description="Error explanation if status is FAILED or STALLED.")
